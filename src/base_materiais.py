def _sanitize_text(value: str) -> str:
    return (
        value.replace("Â", "")
        .replace("Ã‡", "Ç")
        .replace("Ã", "Á")
        .replace("AÃ", "A")
        .strip()
    )


def _parse_tsv_materials() -> list[dict[str, object]]:
    linhas = [linha.strip() for linha in MATERIAIS_TSV.splitlines() if linha.strip()]
    if not linhas:
        return []

    resultado: list[dict[str, object]] = []
    indice = 1
    for linha in linhas[1:]:
        partes = linha.split("\t")
        if len(partes) < 2:
            continue
        descricao = _sanitize_text(partes[0])
        unidade = _sanitize_text(partes[1])
        if not descricao or not unidade:
            continue

        codigo = f"MAT.{indice:04d}"
        cod_servico = "OBR.002"
        if "CABO" in descricao:
            cod_servico = "CAB.001"
        elif "TRAFO" in descricao:
            cod_servico = "OBR.010"

        resultado.append(
            asdict(
                MaterialBase(
                    codigo=codigo,
                    descricao=descricao,
                    unidade=unidade,
                    valor_unitario=0.0,
                    cod_servico=cod_servico,
                    cod_simulador=f"SIM.{indice:04d}",
                )
            )
        )
        indice += 1
    return resultado


